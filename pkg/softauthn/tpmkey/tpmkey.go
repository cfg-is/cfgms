// Package tpmkey holds a WebAuthn credential key inside the host TPM 2.0 and
// produces the TPM attestation for it (WebAuthn attestation format "tpm").
//
// Every function takes a transport.TPM, so the same code runs against
// /dev/tpmrm0 on Linux, TBS on Windows and a software TPM in tests. The
// credential key is a P-256 signing key that is fixedTPM, fixedParent and
// sensitiveDataOrigin under the owner-hierarchy storage primary; only the
// TPM-wrapped public and private blobs ever leave the TPM, and they are usable
// on this TPM only. The attestation key is derived from the endorsement
// hierarchy from a fixed template and is never persisted.
//
// The package keeps no state, and its production API has no way to produce a
// deliberately wrong attestation.
package tpmkey

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/elliptic"
	"encoding/asn1"
	"errors"
	"fmt"
	"io"
	"math/big"

	"github.com/google/go-tpm/tpm2"
	"github.com/google/go-tpm/tpm2/transport"
)

// ErrUnsupported means this operating system has no supported TPM transport.
var ErrUnsupported = errors.New("a TPM is not supported on this operating system")

// Blobs are a credential key's TPM-wrapped form: the marshalled TPM2B_PUBLIC and
// TPM2B_PRIVATE. They hold no key bytes and load only on the TPM that made them.
type Blobs struct {
	Public  []byte
	Private []byte
}

// credentialKeyTemplate is the credential key: fixed to this TPM and its parent,
// generated by the TPM, sign-only, ECDSA over SHA-256 on P-256.
//
// This is the same template as signingKeyTemplate in
// pkg/registration/identity/tpm_linux.go. That helper is unexported and
// Linux-only, and tpmkey must also build for Windows, so the template is kept
// here rather than shared. The duplication gate does not report it as a clone,
// so it carries no //duplication:justified annotation.
func credentialKeyTemplate() tpm2.TPMTPublic {
	return tpm2.TPMTPublic{
		Type:    tpm2.TPMAlgECC,
		NameAlg: tpm2.TPMAlgSHA256,
		ObjectAttributes: tpm2.TPMAObject{
			FixedTPM:            true,
			FixedParent:         true,
			SensitiveDataOrigin: true,
			UserWithAuth:        true,
			NoDA:                true,
			SignEncrypt:         true,
		},
		Parameters: tpm2.NewTPMUPublicParms(tpm2.TPMAlgECC, &tpm2.TPMSECCParms{
			Scheme: tpm2.TPMTECCScheme{
				Scheme: tpm2.TPMAlgECDSA,
				Details: tpm2.NewTPMUAsymScheme(tpm2.TPMAlgECDSA,
					&tpm2.TPMSSigSchemeECDSA{HashAlg: tpm2.TPMAlgSHA256}),
			},
			CurveID: tpm2.TPMECCNistP256,
		}),
	}
}

func flush(t transport.TPM, h tpm2.TPMHandle) {
	_, _ = tpm2.FlushContext{FlushHandle: h}.Execute(t)
}

// passwordAuth is the empty-password authorization every key here uses.
func passwordAuth(h tpm2.TPMHandle, name tpm2.TPM2BName) tpm2.AuthHandle {
	return tpm2.AuthHandle{Handle: h, Name: name, Auth: tpm2.PasswordAuth(nil)}
}

// withParent creates the deterministic storage primary, runs fn, and flushes it.
func withParent(t transport.TPM, fn func(parent tpm2.AuthHandle) error) error {
	prim, err := tpm2.CreatePrimary{
		PrimaryHandle: tpm2.TPMRHOwner,
		InPublic:      tpm2.New2B(tpm2.ECCSRKTemplate),
	}.Execute(t)
	if err != nil {
		return fmt.Errorf("create storage primary: %w", err)
	}
	defer flush(t, prim.ObjectHandle)
	return fn(passwordAuth(prim.ObjectHandle, prim.Name))
}

// withLoadedKey loads the credential key, runs fn with its handle, and flushes
// the key and its parent.
func withLoadedKey(t transport.TPM, b Blobs, fn func(key tpm2.AuthHandle) error) error {
	pub, err := tpm2.Unmarshal[tpm2.TPM2BPublic](b.Public)
	if err != nil {
		return fmt.Errorf("decode key public area: %w", err)
	}
	priv, err := tpm2.Unmarshal[tpm2.TPM2BPrivate](b.Private)
	if err != nil {
		return fmt.Errorf("decode key private blob: %w", err)
	}
	return withParent(t, func(parent tpm2.AuthHandle) error {
		ld, lErr := tpm2.Load{ParentHandle: parent, InPrivate: *priv, InPublic: *pub}.Execute(t)
		if lErr != nil {
			return fmt.Errorf("load key into TPM: %w", lErr)
		}
		defer flush(t, ld.ObjectHandle)
		return fn(passwordAuth(ld.ObjectHandle, ld.Name))
	})
}

// PublicKey returns the P-256 public key in a marshalled TPM2B_PUBLIC.
func PublicKey(publicBlob []byte) (*ecdsa.PublicKey, error) {
	p2b, err := tpm2.Unmarshal[tpm2.TPM2BPublic](publicBlob)
	if err != nil {
		return nil, fmt.Errorf("decode key public area: %w", err)
	}
	pt, err := p2b.Contents()
	if err != nil {
		return nil, fmt.Errorf("decode key public area: %w", err)
	}
	return eccPublicKey(pt, tpm2.TPMECCNistP256)
}

func eccPublicKey(pt *tpm2.TPMTPublic, curve tpm2.TPMECCCurve) (*ecdsa.PublicKey, error) {
	if pt.Type != tpm2.TPMAlgECC {
		return nil, errors.New("TPM key is not an ECC key")
	}
	parms, err := pt.Parameters.ECCDetail()
	if err != nil || parms.CurveID != curve {
		return nil, errors.New("TPM key is not on curve P-256")
	}
	point, err := pt.Unique.ECC()
	if err != nil {
		return nil, fmt.Errorf("read TPM key point: %w", err)
	}
	pub, err := tpm2.ECDSAPub(parms, point)
	if err != nil {
		return nil, fmt.Errorf("TPM key point is not valid: %w", err)
	}
	if pub.Curve != elliptic.P256() {
		return nil, errors.New("TPM key is not on curve P-256")
	}
	return pub, nil
}

// Create makes a new credential key inside the TPM and returns its wrapped blobs
// and public key. The TPM reports the attributes of the key it made; Create
// refuses a key that is not fixedTPM, fixedParent and sensitiveDataOrigin.
func Create(t transport.TPM) (Blobs, *ecdsa.PublicKey, error) {
	var b Blobs
	err := withParent(t, func(parent tpm2.AuthHandle) error {
		rsp, cErr := tpm2.Create{
			ParentHandle: parent,
			InPublic:     tpm2.New2B(credentialKeyTemplate()),
		}.Execute(t)
		if cErr != nil {
			return fmt.Errorf("create credential key: %w", cErr)
		}
		b = Blobs{Public: tpm2.Marshal(rsp.OutPublic), Private: tpm2.Marshal(rsp.OutPrivate)}
		return nil
	})
	if err != nil {
		return Blobs{}, nil, err
	}
	pt, err := tpm2.Unmarshal[tpm2.TPM2BPublic](b.Public)
	if err != nil {
		return Blobs{}, nil, fmt.Errorf("decode key public area: %w", err)
	}
	contents, err := pt.Contents()
	if err != nil {
		return Blobs{}, nil, fmt.Errorf("decode key public area: %w", err)
	}
	attrs := contents.ObjectAttributes
	if !attrs.FixedTPM || !attrs.FixedParent || !attrs.SensitiveDataOrigin {
		return Blobs{}, nil, errors.New("the TPM did not make a fixed, TPM-generated key")
	}
	pub, err := eccPublicKey(contents, tpm2.TPMECCNistP256)
	if err != nil {
		return Blobs{}, nil, err
	}
	return b, pub, nil
}

// signer is a crypto.Signer whose key never leaves the TPM.
type signer struct {
	t     transport.TPM
	blobs Blobs
	pub   *ecdsa.PublicKey
}

// Open returns a crypto.Signer for the credential key in b. Sign asks the TPM
// to sign a 32-byte SHA-256 digest with ECDSA and returns ASN.1 DER; the digest
// is the TPM's hash input directly and nothing is hashed again. The caller
// keeps t open for as long as the signer is used.
func Open(t transport.TPM, b Blobs) (crypto.Signer, error) {
	pub, err := PublicKey(b.Public)
	if err != nil {
		return nil, err
	}
	return &signer{t: t, blobs: Blobs{Public: b.Public, Private: b.Private}, pub: pub}, nil
}

// Public returns the credential public key.
func (s *signer) Public() crypto.PublicKey { return s.pub }

// Sign implements crypto.Signer for a SHA-256 digest.
func (s *signer) Sign(_ io.Reader, digest []byte, opts crypto.SignerOpts) ([]byte, error) {
	if opts == nil || opts.HashFunc() != crypto.SHA256 || len(digest) != 32 {
		return nil, errors.New("the TPM signer signs a 32-byte SHA-256 digest only")
	}
	var der []byte
	err := withLoadedKey(s.t, s.blobs, func(key tpm2.AuthHandle) error {
		rsp, sErr := tpm2.Sign{
			KeyHandle: key,
			Digest:    tpm2.TPM2BDigest{Buffer: digest},
			InScheme: tpm2.TPMTSigScheme{
				Scheme:  tpm2.TPMAlgECDSA,
				Details: tpm2.NewTPMUSigScheme(tpm2.TPMAlgECDSA, &tpm2.TPMSSchemeHash{HashAlg: tpm2.TPMAlgSHA256}),
			},
			Validation: tpm2.TPMTTKHashCheck{Tag: tpm2.TPMSTHashCheck, Hierarchy: tpm2.TPMRHNull},
		}.Execute(s.t)
		if sErr != nil {
			return fmt.Errorf("TPM sign: %w", sErr)
		}
		var eErr error
		der, eErr = ecdsaDER(rsp.Signature)
		return eErr
	})
	if err != nil {
		return nil, err
	}
	return der, nil
}

// ecdsaDER converts a TPM ECDSA signature to ASN.1 DER.
func ecdsaDER(sig tpm2.TPMTSignature) ([]byte, error) {
	ecc, err := sig.Signature.ECDSA()
	if err != nil {
		return nil, fmt.Errorf("decode TPM signature: %w", err)
	}
	return asn1.Marshal(struct{ R, S *big.Int }{
		new(big.Int).SetBytes(ecc.SignatureR.Buffer),
		new(big.Int).SetBytes(ecc.SignatureS.Buffer),
	})
}
