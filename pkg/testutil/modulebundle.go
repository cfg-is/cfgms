package testutil

import (
	"crypto/ed25519"
	"crypto/rand"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	"github.com/cfgis/cfgms/pkg/modules/bundle"
)

// BundleOptions configures NewSignedBundle. Every field is optional.
type BundleOptions struct {
	// Publisher is the manifest publisher and the signing identity (default "cfgms").
	Publisher string
	// Name is the module name (default "testmod").
	Name string
	// Version is an exact semver (default "1.0.0").
	Version string
	// Platforms are the os-arch keys to include (default: the running platform).
	Platforms []string
	// Executors are the manifest executors (default: steward). A controller
	// executor makes the module a workflow module.
	Executors []string
	// ManifestExtra is raw YAML appended to the manifest (top-level keys such as
	// always_pull or observe_when).
	ManifestExtra string
	// Key signs the bundle (default: a fresh key, see SignedBundle.PublicKey).
	Key ed25519.PrivateKey
	// BinaryContent overrides the generated bytes of a platform's binary.
	BinaryContent map[string][]byte
}

// SignedBundle is a signed payload bundle built through the production
// bundle.Assemble and bundle.Sign path, with the key that signed it.
type SignedBundle struct {
	*bundle.Bundle
	PrivateKey ed25519.PrivateKey
	PublicKey  ed25519.PublicKey
}

// BinaryFileName returns the file name NewSignedBundle gives a platform's binary.
func BinaryFileName(name, platform string) string {
	n := "cfgms-module-" + name + "-" + platform
	if strings.HasPrefix(platform, "windows-") {
		n += ".exe"
	}
	return n
}

// NewSignedBundle builds a signed payload Bundle for any publisher name and
// platform set using bundle.Assemble and bundle.Sign — the same code the
// publisher tool runs — so tests never hand-build bundles.
func NewSignedBundle(t testing.TB, opts BundleOptions) *SignedBundle {
	t.Helper()

	if opts.Publisher == "" {
		opts.Publisher = "cfgms"
	}
	if opts.Name == "" {
		opts.Name = "testmod"
	}
	if opts.Version == "" {
		opts.Version = "1.0.0"
	}
	if len(opts.Platforms) == 0 {
		opts.Platforms = []string{runtime.GOOS + "-" + runtime.GOARCH}
	}
	if len(opts.Executors) == 0 {
		opts.Executors = []string{"steward"}
	}
	priv := opts.Key
	if priv == nil {
		var err error
		if _, priv, err = ed25519.GenerateKey(rand.Reader); err != nil {
			t.Fatalf("generate test signing key: %v", err)
		}
	}

	src := t.TempDir()
	manifestPath := filepath.Join(src, bundle.ManifestFileName)
	manifest := fmt.Sprintf("name: %s\nversion: %s\ndescription: test module\npublisher: %s\nexecutors:\n",
		opts.Name, opts.Version, opts.Publisher)
	for _, e := range opts.Executors {
		manifest += "  - " + e + "\n"
	}
	manifest += opts.ManifestExtra
	if err := os.WriteFile(manifestPath, []byte(manifest), 0o600); err != nil {
		t.Fatalf("write test manifest: %v", err)
	}

	spec := bundle.AssembleSpec{ManifestPath: manifestPath, Binaries: map[string]bundle.PlatformBinary{}}
	for _, platform := range opts.Platforms {
		data, ok := opts.BinaryContent[platform]
		if !ok {
			data = []byte(fmt.Sprintf("test module binary %s %s %s", opts.Publisher, opts.Name, platform))
		}
		p := filepath.Join(src, "bin-"+platform)
		if err := os.WriteFile(p, data, 0o600); err != nil {
			t.Fatalf("write test binary: %v", err)
		}
		spec.Binaries[platform] = bundle.PlatformBinary{FileName: BinaryFileName(opts.Name, platform), SourcePath: p}
	}

	b, err := bundle.Assemble(spec)
	if err != nil {
		t.Fatalf("assemble test bundle: %v", err)
	}
	if err := bundle.Sign(b, priv); err != nil {
		t.Fatalf("sign test bundle: %v", err)
	}
	return &SignedBundle{Bundle: b, PrivateKey: priv, PublicKey: priv.Public().(ed25519.PublicKey)}
}

// WriteRoot writes the bundle as an installation root at root (which must not
// exist) through bundle.WriteInstalled.
func (s *SignedBundle) WriteRoot(t testing.TB, root string, opts bundle.WriteOptions) {
	t.Helper()
	if err := bundle.WriteInstalled(s.Bundle, root, opts); err != nil {
		t.Fatalf("write test bundle root: %v", err)
	}
}

// CommitToRepo writes the bundle's full-mode layout into repoDir (created and
// initialised as a git repository if needed), commits it and returns the commit
// id. It stands in for a publisher's git repository in resolver tests.
func (s *SignedBundle) CommitToRepo(t testing.TB, repoDir string) string {
	t.Helper()

	staged := filepath.Join(t.TempDir(), "root")
	s.WriteRoot(t, staged, bundle.WriteOptions{})

	if err := os.MkdirAll(repoDir, 0o750); err != nil {
		t.Fatalf("create repo dir: %v", err)
	}
	git := func(args ...string) string {
		t.Helper()
		full := append([]string{"-C", repoDir,
			"-c", "user.name=cfgms-test", "-c", "user.email=test@example.invalid",
			"-c", "commit.gpgsign=false", "-c", "init.defaultBranch=main"}, args...)
		// #nosec G204 -- fixed git binary; arguments are test-controlled constants and file names.
		out, err := GitCommand(t, "", full...).CombinedOutput()
		if err != nil {
			t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
		}
		return strings.TrimSpace(string(out))
	}
	if _, err := os.Stat(filepath.Join(repoDir, ".git")); err != nil {
		git("init", "-q")
	}

	entries, err := os.ReadDir(staged)
	if err != nil {
		t.Fatalf("list staged root: %v", err)
	}
	add := []string{"add", "--"}
	for _, e := range entries {
		data, err := os.ReadFile(filepath.Join(staged, e.Name())) // #nosec G304 -- test-owned staging dir
		if err != nil {
			t.Fatalf("read staged file: %v", err)
		}
		info, err := e.Info()
		if err != nil {
			t.Fatalf("stat staged file: %v", err)
		}
		name := e.Name()
		if !info.Mode().IsRegular() || !filepath.IsLocal(name) || filepath.Base(name) != name {
			t.Fatalf("staged root entry %q is not a plain regular file", name)
		}
		dest := filepath.Join(repoDir, name)
		// #nosec G703 -- name was validated above as a single local file name read from the test-owned staging root.
		if err := os.WriteFile(dest, data, info.Mode().Perm()); err != nil {
			t.Fatalf("write repo file: %v", err)
		}
		// #nosec G703 -- same validated local file name as the write above.
		if err := os.Chmod(dest, info.Mode().Perm()); err != nil {
			t.Fatalf("chmod repo file: %v", err)
		}
		add = append(add, name)
	}
	git(add...)
	git("commit", "-q", "--allow-empty", "-m", "publish "+s.Manifest.Name+" "+s.Manifest.Version)
	return git("rev-parse", "HEAD")
}
