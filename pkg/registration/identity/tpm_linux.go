// tpmDevicePath is the kernel's resource-managed TPM device. Unlike /dev/tpm0 it
// swaps transient objects in and out, so concurrent users of the TPM do not
// exhaust its object slots.
const tpmDevicePath = "/dev/tpmrm0"

// tpmBlobFileName holds the TPM-wrapped key: the child key's public area and its
// private blob, encrypted by this TPM's storage seed. It contains no usable key
// material on any other machine.
const tpmBlobFileName = "device_identity_tpm.blob"

// tpmOpener opens a TPM transport for one operation. Production opens
// /dev/tpmrm0; tests supply a software TPM so the same code path runs.
type tpmOpener func() (transport.TPMCloser, error)

func openTPMDevice() (transport.TPMCloser, error) { return linuxtpm.Open(tpmDevicePath) }

// defaultTPMOpener is read when the registered backend is probed.
var defaultTPMOpener tpmOpener = openTPMDevice

func init() {
	registerBackend(backend{
		level: ProtectionTPM,
		open: func(_ context.Context, dir string, logger logging.Logger) (KeyStore, error) {
			return newTPMKeyStore(dir, defaultTPMOpener, logger), nil
		},
		remove: removeTPMBlob,
	})
}

// tpmKeyStore keeps the device key as a non-exportable NIST P-256 signing key
// inside the TPM. A deterministic storage primary under the owner hierarchy
// parents the key; only the child's public area and TPM-wrapped private blob are
// persisted (mode 0600). A persistent handle (EvictControl) was not chosen: it
// consumes scarce NV slots shared with other software, can be evicted by anyone
// with owner auth, and cannot be cleaned up by removing a file when an image is
// prepared. The primary is re-derived from the storage seed on each operation,
// and every transient handle is flushed before the operation returns.
type tpmKeyStore struct {
	dir    string
	open   tpmOpener
	logger logging.Logger

	mu       sync.Mutex
	pubBlob  []byte // marshalled TPM2B_PUBLIC
	privBlob []byte // marshalled TPM2B_PRIVATE
	pub      *ecdsa.PublicKey
	deviceID string
}

var _ KeyStore = (*tpmKeyStore)(nil)

func newTPMKeyStore(dir string, open tpmOpener, logger logging.Logger) *tpmKeyStore {
	if logger == nil {
		logger = logging.NewNoopLogger()
	}
	return &tpmKeyStore{dir: dir, open: open, logger: logger}
}

func (ks *tpmKeyStore) blobPath() string { return filepath.Join(ks.dir, tpmBlobFileName) }

// signingKeyTemplate is the child key: fixed to this TPM and parent, generated by
// the TPM, sign-only, ECDSA over SHA-256 on P-256.
func signingKeyTemplate() tpm2.TPMTPublic {
	return tpm2.TPMTPublic{
		Type:    tpm2.TPMAlgECC,
		NameAlg: tpm2.TPMAlgSHA256,
		ObjectAttributes: tpm2.TPMAObject{
			FixedTPM:            true,
			FixedParent:         true,
			SensitiveDataOrigin: true,
			UserWithAuth:        true,
			NoDA:                true,
			SignEncrypt:         true,
		},
		Parameters: tpm2.NewTPMUPublicParms(tpm2.TPMAlgECC, &tpm2.TPMSECCParms{
			Scheme: tpm2.TPMTECCScheme{
				Scheme: tpm2.TPMAlgECDSA,
				Details: tpm2.NewTPMUAsymScheme(tpm2.TPMAlgECDSA,
					&tpm2.TPMSSigSchemeECDSA{HashAlg: tpm2.TPMAlgSHA256}),
			},
			CurveID: tpm2.TPMECCNistP256,
		}),
	}
}

func flush(t transport.TPM, h tpm2.TPMHandle) {
	_, _ = tpm2.FlushContext{FlushHandle: h}.Execute(t)
}

// withParent creates the deterministic storage primary, runs fn, and flushes it.
func withParent(t transport.TPM, fn func(parent tpm2.AuthHandle) error) error {
	prim, err := tpm2.CreatePrimary{
		PrimaryHandle: tpm2.TPMRHOwner,
		InPublic:      tpm2.New2B(tpm2.ECCSRKTemplate),
	}.Execute(t)
	if err != nil {
		return fmt.Errorf("create storage primary: %w", err)
	}
	defer flush(t, prim.ObjectHandle)
	return fn(tpm2.AuthHandle{Handle: prim.ObjectHandle, Name: prim.Name, Auth: tpm2.PasswordAuth(nil)})
}

// createKey makes a new child key under a fresh primary and returns its blobs.
func createKey(t transport.TPM) (pubBlob, privBlob []byte, err error) {
	err = withParent(t, func(parent tpm2.AuthHandle) error {
		rsp, cErr := tpm2.Create{
			ParentHandle: parent,
			InPublic:     tpm2.New2B(signingKeyTemplate()),
		}.Execute(t)
		if cErr != nil {
			return fmt.Errorf("create signing key: %w", cErr)
		}
		pubBlob = tpm2.Marshal(rsp.OutPublic)
		privBlob = tpm2.Marshal(rsp.OutPrivate)
		return nil
	})
	return pubBlob, privBlob, err
}

// withLoadedKey loads the persisted blobs, runs fn with the key handle, and
// flushes both the key and its parent.
func withLoadedKey(t transport.TPM, pubBlob, privBlob []byte, fn func(key tpm2.AuthHandle) error) error {
	pub, err := tpm2.Unmarshal[tpm2.TPM2BPublic](pubBlob)
	if err != nil {
		return fmt.Errorf("decode key public area: %w", err)
	}
	priv, err := tpm2.Unmarshal[tpm2.TPM2BPrivate](privBlob)
	if err != nil {
		return fmt.Errorf("decode key private blob: %w", err)
	}
	return withParent(t, func(parent tpm2.AuthHandle) error {
		ld, lErr := tpm2.Load{ParentHandle: parent, InPrivate: *priv, InPublic: *pub}.Execute(t)
		if lErr != nil {
			return fmt.Errorf("load key into TPM: %w", lErr)
		}
		defer flush(t, ld.ObjectHandle)
		return fn(tpm2.AuthHandle{Handle: ld.ObjectHandle, Name: ld.Name, Auth: tpm2.PasswordAuth(nil)})
	})
}

// publicFromBlob extracts the P-256 public key from a marshalled TPM2B_PUBLIC.
func publicFromBlob(pubBlob []byte) (*ecdsa.PublicKey, error) {
	p2b, err := tpm2.Unmarshal[tpm2.TPM2BPublic](pubBlob)
	if err != nil {
		return nil, fmt.Errorf("decode key public area: %w", err)
	}
	pt, err := p2b.Contents()
	if err != nil {
		return nil, fmt.Errorf("decode key public area: %w", err)
	}
	if pt.Type != tpm2.TPMAlgECC {
		return nil, errors.New("TPM key is not an ECC key")
	}
	parms, err := pt.Parameters.ECCDetail()
	if err != nil || parms.CurveID != tpm2.TPMECCNistP256 {
		return nil, errors.New("TPM key is not on curve P-256")
	}
	pt2, err := pt.Unique.ECC()
	if err != nil {
		return nil, fmt.Errorf("read TPM key point: %w", err)
	}
	if len(pt2.X.Buffer) > 32 || len(pt2.Y.Buffer) > 32 {
		return nil, errors.New("TPM key point has invalid size")
	}
	uncompressed := make([]byte, 65)
	uncompressed[0] = 4
	copy(uncompressed[1+32-len(pt2.X.Buffer):33], pt2.X.Buffer)
	copy(uncompressed[33+32-len(pt2.Y.Buffer):65], pt2.Y.Buffer)
	pub, err := ecdsa.ParseUncompressedPublicKey(elliptic.P256(), uncompressed)
	if err != nil {
		return nil, fmt.Errorf("TPM key point is not on curve: %w", err)
	}
	return pub, nil
}

func encodeBlobFile(pubBlob, privBlob []byte) []byte {
	out := binary.BigEndian.AppendUint32(nil, uint32(len(pubBlob))) //#nosec G115 -- TPM2B_PUBLIC is far below 4 GiB
	out = append(out, pubBlob...)
	return append(out, privBlob...)
}

func decodeBlobFile(data []byte) (pubBlob, privBlob []byte, err error) {
	if len(data) < 4 {
		return nil, nil, errors.New("TPM key file truncated")
	}
	n := binary.BigEndian.Uint32(data)
	rest := data[4:]
	// Widening uint32 and int to int64 is lossless on every supported
	// platform, so the bound check cannot overflow.
	if int64(n) > int64(len(rest)) {
		return nil, nil, errors.New("TPM key file corrupt")
	}
	return rest[:n], rest[n:], nil
}

// writeBlobFile atomically replaces the blob file (mode 0600).
func (ks *tpmKeyStore) writeBlobFile(pubBlob, privBlob []byte) error {
	if err := os.MkdirAll(ks.dir, 0700); err != nil {
		return fmt.Errorf("create identity dir: %w", err)
	}
	path := ks.blobPath()
	tmp := path + ".tmp"
	_ = os.Remove(tmp)                                                  // a stale file could carry looser permissions
	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600) //#nosec G304 -- fixed name under the identity directory
	if err != nil {
		return fmt.Errorf("write TPM key file: %w", err)
	}
	_, wErr := f.Write(encodeBlobFile(pubBlob, privBlob))
	if sErr := f.Sync(); wErr == nil {
		wErr = sErr
	}
	if cErr := f.Close(); wErr == nil {
		wErr = cErr
	}
	if wErr != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("write TPM key file: %w", wErr)
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("commit TPM key file: %w", err)
	}
	return nil
}

func (ks *tpmKeyStore) setCurrentLocked(pubBlob, privBlob []byte, pub *ecdsa.PublicKey) error {
	id, err := ComputeDeviceID(AlgorithmECDSAP256, pub)
	if err != nil {
		return err
	}
	ks.pubBlob, ks.privBlob, ks.pub, ks.deviceID = pubBlob, privBlob, pub, id
	return nil
}

func (ks *tpmKeyStore) openTransport() (transport.TPMCloser, error) {
	t, err := ks.open()
	if err != nil {
		return nil, fmt.Errorf("open TPM: %w", err)
	}
	return t, nil
}

// GenerateOrLoad loads the persisted key, or creates one when no key file exists.
// A key file that cannot be loaded is an error: generating a replacement would
// change the DeviceID and orphan the enrolment.
func (ks *tpmKeyStore) GenerateOrLoad(_ context.Context) (crypto.PublicKey, Algorithm, error) {
	ks.mu.Lock()
	defer ks.mu.Unlock()

	data, err := os.ReadFile(ks.blobPath()) //#nosec G304 -- fixed name under the identity directory
	switch {
	case err == nil:
		pubBlob, privBlob, dErr := decodeBlobFile(data)
		if dErr != nil {
			return nil, "", dErr
		}
		pub, lErr := ks.loadLocked(pubBlob, privBlob)
		if lErr != nil {
			return nil, "", lErr
		}
		return pub, AlgorithmECDSAP256, nil
	case errors.Is(err, os.ErrNotExist):
		pub, gErr := ks.generateLocked()
		if gErr != nil {
			return nil, "", gErr
		}
		return pub, AlgorithmECDSAP256, nil
	default:
		return nil, "", fmt.Errorf("read TPM key file: %w", err)
	}
}

// loadLocked proves the blobs load in this TPM, then makes them current.
func (ks *tpmKeyStore) loadLocked(pubBlob, privBlob []byte) (*ecdsa.PublicKey, error) {
	pub, err := publicFromBlob(pubBlob)
	if err != nil {
		return nil, err
	}
	t, err := ks.openTransport()
	if err != nil {
		return nil, err
	}
	defer func() { _ = t.Close() }()
	if err := withLoadedKey(t, pubBlob, privBlob, func(tpm2.AuthHandle) error { return nil }); err != nil {
		return nil, err
	}
	if err := ks.setCurrentLocked(pubBlob, privBlob, pub); err != nil {
		return nil, err
	}
	return pub, nil
}

// generateLocked creates a key, persists it atomically, then makes it current.
func (ks *tpmKeyStore) generateLocked() (*ecdsa.PublicKey, error) {
	t, err := ks.openTransport()
	if err != nil {
		return nil, err
	}
	defer func() { _ = t.Close() }()
	pubBlob, privBlob, err := createKey(t)
	if err != nil {
		return nil, err
	}
	pub, err := publicFromBlob(pubBlob)
	if err != nil {
		return nil, err
	}
	if err := ks.writeBlobFile(pubBlob, privBlob); err != nil {
		return nil, err
	}
	if err := ks.setCurrentLocked(pubBlob, privBlob, pub); err != nil {
		return nil, err
	}
	return pub, nil
}

// Regenerate replaces the key with a new one; the old blobs are replaced only
// once the new ones are durably written (ADR-034 §4).
func (ks *tpmKeyStore) Regenerate(_ context.Context) (crypto.PublicKey, Algorithm, error) {
	ks.mu.Lock()
	defer ks.mu.Unlock()
	pub, err := ks.generateLocked()
	if err != nil {
		return nil, "", err
	}
	return pub, AlgorithmECDSAP256, nil
}

// RemoveKey deletes the persisted blobs and forgets the in-memory key.
func (ks *tpmKeyStore) RemoveKey() error {
	ks.mu.Lock()
	defer ks.mu.Unlock()
	if err := removeTPMBlob(ks.dir); err != nil {
		return err
	}
	ks.pubBlob, ks.privBlob, ks.pub, ks.deviceID = nil, nil, nil, ""
	return nil
}

func removeTPMBlob(dir string) error {
	err := os.Remove(filepath.Join(dir, tpmBlobFileName))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("remove TPM device key: %w", err)
	}
	return nil
}

// Algorithm returns AlgorithmECDSAP256.
func (ks *tpmKeyStore) Algorithm() Algorithm { return AlgorithmECDSAP256 }

// ProtectionLevel returns ProtectionTPM.
func (ks *tpmKeyStore) ProtectionLevel() ProtectionLevel { return ProtectionTPM }

// DeviceID returns the SHA-256 of the PKIX DER public key, or "" before GenerateOrLoad.
func (ks *tpmKeyStore) DeviceID() string {
	ks.mu.Lock()
	defer ks.mu.Unlock()
	return ks.deviceID
}

// PublicKey returns the *ecdsa.PublicKey, or nil before GenerateOrLoad.
func (ks *tpmKeyStore) PublicKey() crypto.PublicKey {
	ks.mu.Lock()
	defer ks.mu.Unlock()
	if ks.pub == nil {
		return nil
	}
	return ks.pub
}

// Sign signs the 32-byte digest in the TPM with ECDSA and returns ASN.1 DER. The
// digest is the TPM's hash input directly; nothing is hashed again (ADR-011
// Amendment 3).
func (ks *tpmKeyStore) Sign(digest []byte) ([]byte, error) {
	if len(digest) != 32 {
		return nil, fmt.Errorf("digest must be 32 bytes, got %d", len(digest))
	}
	ks.mu.Lock()
	defer ks.mu.Unlock()
	if ks.pub == nil {
		return nil, errors.New("device identity key not loaded: call GenerateOrLoad first")
	}
	t, err := ks.openTransport()
	if err != nil {
		return nil, err
	}
	defer func() { _ = t.Close() }()

	var der []byte
	err = withLoadedKey(t, ks.pubBlob, ks.privBlob, func(key tpm2.AuthHandle) error {
		rsp, sErr := tpm2.Sign{
			KeyHandle: key,
			Digest:    tpm2.TPM2BDigest{Buffer: digest},
			InScheme: tpm2.TPMTSigScheme{
				Scheme:  tpm2.TPMAlgECDSA,
				Details: tpm2.NewTPMUSigScheme(tpm2.TPMAlgECDSA, &tpm2.TPMSSchemeHash{HashAlg: tpm2.TPMAlgSHA256}),
			},
			Validation: tpm2.TPMTTKHashCheck{Tag: tpm2.TPMSTHashCheck, Hierarchy: tpm2.TPMRHNull},
		}.Execute(t)
		if sErr != nil {
			return fmt.Errorf("TPM sign: %w", sErr)
		}
		sig, eErr := rsp.Signature.Signature.ECDSA()
		if eErr != nil {
			return fmt.Errorf("decode TPM signature: %w", eErr)
		}
		der, eErr = asn1.Marshal(struct{ R, S *big.Int }{
			new(big.Int).SetBytes(sig.SignatureR.Buffer),
			new(big.Int).SetBytes(sig.SignatureS.Buffer),
		})
		return eErr
	})
	if err != nil {
		return nil, err
	}
	return der, nil
}
