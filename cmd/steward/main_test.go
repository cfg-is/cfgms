// TestAutoGeneratedPasswordNotice_NoPasswordValue is a regression test for the
// CodeQL go/clear-text-logging (CWE-312/532) finding on PR #1860: the operator
// notice printed after an auto-generated password install must not contain the
// password value itself. Operators retrieve the value from the secret store.
func TestAutoGeneratedPasswordNotice_NoPasswordValue(t *testing.T) {
	notice := autoGeneratedPasswordNotice()

	// Notice must mention the secret store key so operators know where to look.
	assert.Contains(t, notice, "hyperv/winrm_pass",
		"notice must name the secret store key so operators can retrieve the password")

	// Notice must not contain a "%s" format verb — if it did, that would be a
	// sign someone is passing the password value into a format call.
	assert.NotContains(t, notice, "%s",
		"notice must be a literal string, never a format string with a password placeholder")

	// Generate a recognisable password value and assert it does not appear in
	// the notice when paired with a typical auto-generate flow.
	pass, autoGenerated, err := resolveWinRMPassword(false)
	require.NoError(t, err)
	require.True(t, autoGenerated)
	require.Len(t, pass, 32)
	assert.NotContains(t, notice, pass,
		"notice must never contain the auto-generated password value")
}

func TestResolveWinRMPassword_Stdin(t *testing.T) {
	// Redirect stdin to a pipe for the test.
	r, w, err := os.Pipe()
	require.NoError(t, err)
	oldStdin := os.Stdin
	os.Stdin = r
	defer func() { os.Stdin = oldStdin }()

	_, writeErr := w.WriteString("secretFromStdin\n")
	require.NoError(t, writeErr)
	require.NoError(t, w.Close())

	pass, autoGenerated, err := resolveWinRMPassword(true)
	require.NoError(t, err)
	assert.False(t, autoGenerated, "must report not auto-generated when fromStdin=true")
	assert.Equal(t, "secretFromStdin", pass)
}

func TestResolveWinRMPassword_StdinEmpty(t *testing.T) {
	// Stdin is empty (immediate EOF) → error.
	r, w, err := os.Pipe()
	require.NoError(t, err)
	require.NoError(t, w.Close()) // close immediately to produce EOF
	oldStdin := os.Stdin
	os.Stdin = r
	defer func() { os.Stdin = oldStdin }()

	_, _, err = resolveWinRMPassword(true)
	require.Error(t, err, "empty stdin must return an error")
	assert.Contains(t, err.Error(), "stdin is empty")
}

