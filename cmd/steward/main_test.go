func TestGenerateRandomPassword(t *testing.T) {
	pass, err := generateRandomPassword(32)
	require.NoError(t, err)
	assert.Len(t, pass, 32, "generated password must be exactly 32 characters")

	// All characters must be alphanumeric.
	for _, c := range pass {
		assert.True(t,
			(c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9'),
			"generated password must only contain alphanumeric characters, got %q", c)
	}

	// Two consecutive calls must produce different passwords (with overwhelming probability).
	pass2, err := generateRandomPassword(32)
	require.NoError(t, err)
	assert.NotEqual(t, pass, pass2, "consecutive passwords must differ")
}

