// cloneBody returns a function body long enough to exceed a small threshold.
func cloneBody(name string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "package p\n\nfunc %s(x int) int {\n", name)
	for i := 0; i < 12; i++ {
		fmt.Fprintf(&b, "\tx = x*%d + (x ^ %d)\n", i+2, i+3)
	}
	b.WriteString("\treturn x\n}\n")
	return b.String()
}

func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for p, src := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o750))
		require.NoError(t, os.WriteFile(full, []byte(src), 0o600))
	}
	return root
}

func runDup(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var so, se bytes.Buffer
	code := duplicationCmd(args, &so, &se)
	return code, so.String(), se.String()
}

func readDup(t *testing.T, path string) dupmetrics.Report {
	t.Helper()
	f, err := os.Open(path) // #nosec G304 -- test temp path
	require.NoError(t, err)
	defer func() { _ = f.Close() }()
	r, err := dupmetrics.Read(f)
	require.NoError(t, err)
	return r
}

func TestDuplicationReportExcludesNonProduction(t *testing.T) {
	clone := cloneBody("F")
	root := writeTree(t, map[string]string{
		"go.mod":          "module example.com/m\n",
		"pkg/a/a.go":      clone,
		"pkg/b/b.go":      clone,
		"pkg/c/c_test.go": clone,
		"pkg/c/c.pb.go":   clone,
		"pkg/c/gen.go":    "// Code generated by x. DO NOT EDIT.\n" + clone,
		"test/t.go":       clone,
		"web/w.go":        clone,
		"scripts/s.go":    clone,
		".hidden/h.go":    clone,
		"vendor/v/v.go":   clone,
		"nested/go.mod":   "module example.com/nested\n",
		"nested/n.go":     clone,
	})
	out := filepath.Join(root, "out", "m.json")
	code, stdout, stderr := runDup(t, "report", "-root", root, "-out", out, "-threshold", "20", "-base-commit", "deadbeef")
	require.Equal(t, exitOK, code, stderr)
	assert.Contains(t, stdout, "duplicated")

	r := readDup(t, out)
	assert.Equal(t, "deadbeef", r.BaseCommit)
	assert.Equal(t, 20, r.Threshold)
	files := map[string]bool{}
	for _, run := range r.Runs {
		files[run.File] = true
	}
	assert.Equal(t, map[string]bool{"pkg/a/a.go": true, "pkg/b/b.go": true}, files)
	assert.Equal(t, 2, r.Aggregate.Runs)
	assert.Equal(t, 2, r.Aggregate.ProductionFiles)
}

func TestDuplicationByPackageSumsToAggregate(t *testing.T) {
	clone := cloneBody("F")
	root := writeTree(t, map[string]string{
		"pkg/a/a.go": clone,
		"pkg/a/b.go": clone,
		"pkg/b/c.go": cloneBody("G"),
		"pkg/b/d.go": cloneBody("H"),
		"pkg/e/e.go": "package e\n\nfunc E() int { return 1 }\n",
	})
	out := filepath.Join(t.TempDir(), "m.json")
	code, stdout, stderr := runDup(t, "report", "-root", root, "-out", out, "-threshold", "20", "-base-commit", "x")
	require.Equal(t, exitOK, code, stderr)

	r := readDup(t, out)
	require.Contains(t, r.ByPackage, "pkg/a")
	require.Contains(t, r.ByPackage, "pkg/b")
	assert.NotContains(t, r.ByPackage, "pkg/e")
	sum := 0
	for _, n := range r.ByPackage {
		sum += n
	}
	assert.Positive(t, sum)
	assert.Equal(t, r.Aggregate.DuplicatedLines, sum)
	assert.Equal(t, 5, r.Aggregate.ProductionFiles)
	assert.Positive(t, r.Aggregate.ProductionLines)
	assert.Contains(t, stdout, "pkg/a")
	assert.Contains(t, stdout, "pkg/b")
}

func TestDuplicationInvalidAnnotationListedAndPrinted(t *testing.T) {
	root := writeTree(t, map[string]string{
		"pkg/a/a.go": "package a\n\n//duplication:justified pkg/zzz/none.go -- because\nfunc A() int { return 1 }\n",
	})
	out := filepath.Join(t.TempDir(), "m.json")
	code, stdout, stderr := runDup(t, "report", "-root", root, "-out", out, "-threshold", "20", "-base-commit", "x")
	require.Equal(t, exitOK, code, stderr)
	r := readDup(t, out)
	require.Len(t, r.InvalidAnnotations, 1)
	assert.Equal(t, "pkg/a/a.go", r.InvalidAnnotations[0].File)
	assert.Equal(t, 3, r.InvalidAnnotations[0].Line)
	assert.Contains(t, stdout, "pkg/a/a.go:3")
}

func TestDuplicationUnknownVerbAndUsage(t *testing.T) {
	code, _, stderr := runDup(t, "bogus")
	assert.Equal(t, exitError, code)
	assert.Contains(t, stderr, "unknown")
	code, _, _ = runDup(t)
	assert.Equal(t, exitError, code)
	code, _, _ = runDup(t, "report", "-nope")
	assert.Equal(t, exitError, code)
}

func TestDuplicationReportBadInputs(t *testing.T) {
	root := writeTree(t, map[string]string{"a.go": "package a\n"})
	out := filepath.Join(t.TempDir(), "m.json")
	code, _, stderr := runDup(t, "report", "-root", root, "-out", out, "-threshold", "1", "-base-commit", "x")
	assert.Equal(t, exitError, code)
	assert.Contains(t, stderr, "threshold")

	missing := filepath.Join(t.TempDir(), "nope")
	code, _, _ = runDup(t, "report", "-root", missing, "-out", out, "-base-commit", "x")
	assert.Equal(t, exitError, code)
}
