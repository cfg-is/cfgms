// analyzeSrc analyses one synthetic file and returns its records.
func analyzeSrc(t *testing.T, name, src string) []Function {
	t.Helper()
	fns, err := Analyze(fstest.MapFS{name: {Data: []byte(src)}}, []string{"."})
	require.NoError(t, err)
	return fns
}

func TestAnalyzeRecordFields(t *testing.T) {
	fns := analyzeSrc(t, "pkg/a/a.go", "package a\n\nfunc F(x int) int {\n\treturn x\n}\n")
	require.Len(t, fns, 1)
	fn := fns[0]
	assert.Equal(t, "pkg/a", fn.Package)
	assert.Equal(t, "pkg/a/a.go", fn.File)
	assert.Equal(t, 3, fn.Line)
	assert.Equal(t, "", fn.Recv)
	assert.Equal(t, "F", fn.Name)
	assert.Equal(t, "pkg/a/a.go::.F#0", fn.Identity)
	assert.Equal(t, 1, fn.CC)
	assert.Equal(t, 1, fn.DistinctOperators)
	assert.Equal(t, 1, fn.DistinctOperands)
}

func TestAnalyzeSkipsBodylessAndSortsOutput(t *testing.T) {
	fns := analyzeSrc(t, "b.go", "package a\n\nfunc Ext()\n\nfunc Z() {}\n\nfunc A() {}\n")
	require.Len(t, fns, 2)
	assert.Equal(t, "A", fns[0].Name)
	assert.Equal(t, "Z", fns[1].Name)
}

func TestAnalyzeExclusions(t *testing.T) {
	const src = "package a\n\nfunc F() {}\n"
	fsys := fstest.MapFS{
		"pkg/keep.go":                       {Data: []byte(src)},
		"pkg/x_test.go":                     {Data: []byte(src)},
		"pkg/x.pb.go":                       {Data: []byte(src)},
		"pkg/gen.go":                        {Data: []byte("// Code generated by tool. DO NOT EDIT.\n\npackage a\n\nfunc G() {}\n")},
		"test/t.go":                         {Data: []byte(src)},
		"web/w.go":                          {Data: []byte(src)},
		"scripts/s.go":                      {Data: []byte(src)},
		".claude/worktrees/c.go":            {Data: []byte(src)},
		"pkg/.cache/c.go":                   {Data: []byte(src)},
		"pkg/vendor/v.go":                   {Data: []byte(src)},
		"pkg/node_modules/n.go":             {Data: []byte(src)},
		"pkg/bin/b.go":                      {Data: []byte(src)},
		"pkg/build/b.go":                    {Data: []byte(src)},
		"pkg/data/d.go":                     {Data: []byte(src)},
		"examples/security-fixes/go.mod":    {Data: []byte("module x\n")},
		"examples/security-fixes/sec.go":    {Data: []byte(src)},
		"examples/security-fixes/sub/in.go": {Data: []byte(src)},
		"go.mod":                            {Data: []byte("module y\n")},
	}
	fns, err := Analyze(fsys, []string{"."})
	require.NoError(t, err)
	require.Len(t, fns, 1)
	assert.Equal(t, "pkg/keep.go", fns[0].File)
}

func TestAnalyzeParseError(t *testing.T) {
	_, err := Analyze(fstest.MapFS{"a.go": {Data: []byte("package")}}, []string{"."})
	assert.Error(t, err)
}
