// to regenerate the golden fixture. It is not a test: it is invoked from
// TestRouteTableParity when CFGMS_REGEN_GOLDEN_ROUTES is set, so the fixture can be
// regenerated deterministically alongside the assertion that consumes it.
func formatGoldenRouteTable(entries []routeEntry) string {
	var sb strings.Builder
	sb.WriteString("var goldenRouteTable = []string{\n")
	for _, e := range entries {
		fmt.Fprintf(&sb, "\t%q,\n", e.String())
	}
	sb.WriteString("}\n")
	return sb.String()
}
