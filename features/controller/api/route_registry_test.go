// routeEntry records one {method, path-template} pair from a mux.Router.Walk.
type routeEntry struct {
	method string
	path   string
}

func (r routeEntry) String() string { return r.method + " " + r.path }

// walkRoutes returns all {method, path-template} pairs registered on router, sorted.
func walkRoutes(t *testing.T, router *mux.Router) []routeEntry {
	t.Helper()
	var entries []routeEntry
	err := router.Walk(func(route *mux.Route, _ *mux.Router, _ []*mux.Route) error {
		tpl, err := route.GetPathTemplate()
		if err != nil {
			return nil // skip routes without a path template (e.g. MethodNotAllowed)
		}
		methods, err := route.GetMethods()
		if err != nil || len(methods) == 0 {
			// Route has no explicit methods — record with empty method marker.
			entries = append(entries, routeEntry{"*", tpl})
			return nil
		}
		for _, m := range methods {
			entries = append(entries, routeEntry{m, tpl})
		}
		return nil
	})
	require.NoError(t, err)
	sort.Slice(entries, func(i, j int) bool {
		si, sj := entries[i].String(), entries[j].String()
		return si < sj
	})
	return entries
}

