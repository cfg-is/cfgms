// TestRouteTableParity verifies that the refactored self-registering route architecture
// produces exactly the same {method, path-template} set as the pre-refactor inline code.
// The golden fixture was generated by running walkRoutes against the pre-refactor server.
func TestRouteTableParity(t *testing.T) {
	s := setupRouteTestServer(t)
	router, ok := s.GetRouter().(*mux.Router)
	require.True(t, ok, "GetRouter must return *mux.Router")

	got := walkRoutes(t, router)
	var gotStrings []string
	for _, e := range got {
		gotStrings = append(gotStrings, e.String())
	}

	// Regeneration path: emit the fixture source for a copy/paste update when the
	// route table intentionally changes. Off by default so CI asserts, not prints.
	if os.Getenv("CFGMS_REGEN_GOLDEN_ROUTES") != "" {
		t.Log("\n" + formatGoldenRouteTable(got))
	}

	// Convert golden to sorted slice for comparison.
	golden := make([]string, len(goldenRouteTable))
	copy(golden, goldenRouteTable)
	sort.Strings(golden)

	assert.Equal(t, golden, gotStrings,
		"route table mismatch: routes added or removed during refactor")
}

// TestLiveDispatchAmbiguousPrefixes verifies that gorilla/mux routes requests to the
// correct handler even when two path prefixes share a string-prefix relationship
// (/clusters vs /cluster, /configs vs /config, /stewards/refresh/... vs /stewards/{id}).
// gorilla/mux v1.8 treats subrouters as matchers; a subrouter with no matching route
// causes the parent to backtrack and try the next route — so registration order among
// the extracted files does not affect correctness.
func TestLiveDispatchAmbiguousPrefixes(t *testing.T) {
	s := setupRouteTestServer(t)

	type routeCheck struct {
		method      string
		path        string
		description string
	}

	// All these routes must be FOUND (401/403 — auth ran but rejected — not 404/405).
	// 404 means routing failed; 405 means wrong method reached wrong subrouter.
	checks := []routeCheck{
		// /clusters prefix vs /cluster prefix
		{"GET", "/api/v1/clusters", "/clusters → clusters subrouter (not clusterRouter)"},
		{"GET", "/api/v1/clusters/mycluster", "/clusters/{name} → clusters subrouter"},
		{"POST", "/api/v1/cluster/nodes/x/drain", "/cluster/nodes/... → clusterRouter"},
		{"POST", "/api/v1/cluster/nodes/x/decommission", "/cluster/nodes/... → clusterRouter"},

		// /configs direct vs /config subrouter (cfgPush)
		{"GET", "/api/v1/configs", "/configs → direct api.Handle"},
		{"GET", "/api/v1/configs/abc/deployments", "/configs/{id}/deployments → direct api.Handle"},
		{"POST", "/api/v1/config/push", "/config/push → cfgPush subrouter"},
		{"GET", "/api/v1/config/push/abc", "/config/push/{id} → cfgPush subrouter"},

		// /stewards/refresh/... direct vs /stewards/{id} subrouter
		{"GET", "/api/v1/stewards/refresh/pending", "/stewards/refresh/pending → direct"},
		{"POST", "/api/v1/stewards/refresh/abc/approve", "/stewards/refresh/{id}/approve → direct"},
		{"POST", "/api/v1/stewards/refresh/abc/reject", "/stewards/refresh/{id}/reject → direct"},
		{"GET", "/api/v1/stewards/connections/all", "/stewards/connections/all → stewards subrouter"},
		{"GET", "/api/v1/stewards/mysw/connection", "/stewards/{id}/connection → stewards subrouter"},

		// /tenants/{id} vs /tenants/{tenant_path:.+}/refresh-policy
		{"GET", "/api/v1/tenants/root", "/tenants/{id} → tenants subrouter"},
		{"GET", "/api/v1/tenants/root/child/refresh-policy", "/tenants/.../refresh-policy → tenants subrouter"},
		{"PUT", "/api/v1/tenants/root/refresh-policy", "PUT /tenants/{tenant_path:.+}/refresh-policy"},

		// /stewards/upgrade vs /stewards/{id}
		{"POST", "/api/v1/stewards/upgrade", "/stewards/upgrade → stewardUpgrade subrouter"},
		{"GET", "/api/v1/stewards/upgrade/abc", "/stewards/upgrade/{id} → stewardUpgrade subrouter"},
	}

	for _, c := range checks {
		t.Run(c.description, func(t *testing.T) {
			req := httptest.NewRequest(c.method, c.path, nil)
			w := httptest.NewRecorder()
			s.GetRouter().ServeHTTP(w, req)
			resp := w.Result()
			assert.NotEqual(t, http.StatusNotFound, resp.StatusCode,
				"route not found: %s %s", c.method, c.path)
			assert.NotEqual(t, http.StatusMethodNotAllowed, resp.StatusCode,
				"method not allowed (routing failed): %s %s", c.method, c.path)
		})
	}
}

// TestClustersClusterRouterOrderIndependence verifies that /clusters and /cluster
// route correctly regardless of which registrar runs first. It builds two temporary
// routers with the two registrars in opposite orders and confirms each router routes
// both path families to the correct subrouter.
func TestClustersClusterRouterOrderIndependence(t *testing.T) {
	s := setupRouteTestServer(t)

	buildRouter := func(first, second RouteRegistrarFunc) *mux.Router {
		r := mux.NewRouter()
		api := r.PathPrefix("/api/v1").Subrouter()
		first(s, api)
		second(s, api)
		return r
	}

	for _, tc := range []struct {
		name   string
		router *mux.Router
	}{
		{"clusters-first", buildRouter(registerClusterRoutes, registerClusterLifecycleRoutes)},
		{"cluster-lifecycle-first", buildRouter(registerClusterLifecycleRoutes, registerClusterRoutes)},
	} {
		t.Run(tc.name, func(t *testing.T) {
			for _, check := range []struct{ method, path string }{
				{"GET", "/api/v1/clusters"},
				{"GET", "/api/v1/clusters/myname"},
				{"POST", "/api/v1/cluster/nodes/x/drain"},
				{"POST", "/api/v1/cluster/nodes/x/decommission"},
			} {
				req := httptest.NewRequest(check.method, check.path, nil)
				w := httptest.NewRecorder()
				tc.router.ServeHTTP(w, req)
				resp := w.Result()
				// 404 means routing broke; any other status (including 401, 405 on
				// wrong method to same route) means the route was found.
				assert.NotEqual(t, http.StatusNotFound, resp.StatusCode,
					"[%s] route not found: %s %s", tc.name, check.method, check.path)
			}
		})
	}
}

// TestIndependentRegistrars verifies that two unrelated features can each add a route
// via RegisterRoutes without editing server.go, route_registry.go, or each other.
// This is the retirement condition for the file-conflict-only dependency class (#2765→#2761).
func TestIndependentRegistrars(t *testing.T) {
	const (
		pathA = "/api/v1/test-feature-alpha/status"
		pathB = "/api/v1/test-feature-beta/status"
	)

	hitA := false
	hitB := false

	handlerA := http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		hitA = true
		w.WriteHeader(http.StatusOK)
	})
	handlerB := http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		hitB = true
		w.WriteHeader(http.StatusOK)
	})

	// Build a minimal router that only contains the two test registrars,
	// without touching the real routeRegistrars slice.
	r := mux.NewRouter()
	api := r.PathPrefix("/api/v1").Subrouter()

	registrarA := RouteRegistrarFunc(func(_ *Server, api *mux.Router) {
		sub := api.PathPrefix("/test-feature-alpha").Subrouter()
		sub.Handle("/status", handlerA).Methods("GET")
	})
	registrarB := RouteRegistrarFunc(func(_ *Server, api *mux.Router) {
		sub := api.PathPrefix("/test-feature-beta").Subrouter()
		sub.Handle("/status", handlerB).Methods("GET")
	})

	// Mirrors what setupRouter's loop does with two independently-registered features.
	for _, reg := range []RouteRegistrarFunc{registrarA, registrarB} {
		reg(nil, api)
	}

	for _, tc := range []struct {
		path string
		hit  *bool
	}{
		{pathA, &hitA},
		{pathB, &hitB},
	} {
		req := httptest.NewRequest("GET", tc.path, nil)
		w := httptest.NewRecorder()
		r.ServeHTTP(w, req)
		assert.Equal(t, http.StatusOK, w.Code, "expected 200 for %s", tc.path)
		assert.True(t, *tc.hit, "handler not reached for %s", tc.path)
	}
}

